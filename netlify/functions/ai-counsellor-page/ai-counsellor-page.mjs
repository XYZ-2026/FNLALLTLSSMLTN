let cached = null; // reused while this function instance stays warm

export default async function handler(req) {
  if (req.method !== 'GET' && req.method !== 'HEAD') return new Response('Method not allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
  const url = new URL(req.url);
  // One indexable address only.
  if (url.pathname === '/ai-counsellor') return new Response(null, { status: 301, headers: { Location: '/ai-counsellor.html' } });
  const page = cached || renderPage();
  if (page.complete) cached = page;
  return new Response(req.method === 'HEAD' ? null : page.html, {
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'public, max-age=0, must-revalidate',
      // Served from Netlify's CDN between deploys; a degraded render is kept only briefly.
      'Netlify-CDN-Cache-Control': page.complete ? 'public, durable, s-maxage=86400, stale-while-revalidate=604800' : 'public, s-maxage=60',
      'X-Content-Type-Options': 'nosniff',
    },
  });
}
