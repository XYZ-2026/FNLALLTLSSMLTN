/* ───────── Data shown in the HTML ───────── */
function topBy(rows, key, better, n) {
  const best = new Map();
  for (const r of rows) {
    const prev = best.get(r.college);
    if (!prev || better(r[key], prev[key])) best.set(r.college, r);
  }
  return [...best.values()].sort((a, b) => (better(a[key], b[key]) ? -1 : 1)).slice(0, n);
}
function cetRows() {
  return topBy(D.mhtRound(1).filter((r) => r.cat === 'GOPENS' && r.pct != null && r.rank != null && /^computer (science|engineering)/i.test(r.branch)), 'pct', (a, b) => a > b, 10);
}
function nitRows() {
  return topBy(D.josaa().filter((r) => r.type === 'NIT' && r.quota === 'OS' && r.cat === 'OPEN' && r.gender === 'Gender-Neutral' && r.closing && /^Computer Science and Engineering \(4 Years/.test(r.branch)), 'closing', (a, b) => a < b, 10);
}
function table(caption, head, rows) {
  if (!rows.length) return '';
  return `<div class="tw"><table><caption>${esc(caption)}</caption><thead><tr>${head.map((h) => `<th scope="col">${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`;
}
function dataSection() {
  const cet = table('MHT-CET 2026 CAP Round 1: closing cutoffs for Computer branches (GOPENS, state-level open seats)', ['College', 'Branch', 'Percentile', 'Merit rank'],
    cetRows().map((r) => [tidy(r.college), r.branch, r.pct.toFixed(2), int(r.rank)]));
  const nit = table('JoSAA 2026: NIT Computer Science closing ranks in the final round (OPEN, Other State, gender-neutral)', ['Institute', 'Round 1', 'Final round'],
    nitRows().map((r) => [tidy(r.college), r.rounds[0] ? int(r.rounds[0]) : '–', int(r.closing)]));
  if (!cet && !nit) return '';
  return `<section aria-labelledby="cutoffs"><h2 id="cutoffs">2026 cutoffs at a glance</h2><p>Highest Computer cutoffs among the seat types named in each table, from 2026 counselling. Ask the counsellor for your own category, branch, home university or city.</p>${cet}${nit}</section>`;
}

